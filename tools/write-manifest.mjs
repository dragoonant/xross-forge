// Fills data/art-manifest.js from the delivery files that exist (never from a wish list):
//   XS.ART[<key>] = { file: "art/cards/<key with / as __>.webp" | "art/ui/<name>.webp",
//                     kind: "leader" | "leader-awakened" | "card" | "ui", prompt: "<prompt id = the key>" }
// The prompt id is the key in tools/out/art-prompts.json; the prompts rebuild deterministically from
// data/art-identity.js + STYLE (tools/build-art-prompts.mjs), and each real call is in docs/art-ledger.json
// with its seed and a hash of the prompt. Keys with no file are simply absent: the UI reports a missing
// entry, it does not hide it (check-art lists them).
//   node tools/write-manifest.mjs [--mock | --art-root <dir>]   (--mock writes <scratch>/data/art-manifest.js)
import fs from 'node:fs';
import path from 'node:path';
import { parseArgs, artPaths, loadModel, faceKeys, uiKeys, kindOf, keyOfDeliveryRel, rel } from './art/lib.mjs';

const args = parseArgs(process.argv.slice(2), ['mock']);
const P = artPaths(args);
const M = loadModel();
const known = new Set([...faceKeys(M.CARDS), ...uiKeys(M.IDENT)]);
const art = {};
let strays = 0;
for (const dir of ['cards', 'ui']) {
  const d = path.join(P.root, 'art', dir);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d).filter((x) => x.endsWith('.webp') && fs.statSync(path.join(d, x)).size > 0).sort()) {
    const r = `art/${dir}/${f}`;
    const key = keyOfDeliveryRel(r);
    if (!key || !known.has(key)) { console.log(`write-manifest: skipping ${r} (names no known key)`); strays++; continue; }
    art[key] = { file: r, kind: kindOf(key, M.CARDS), prompt: key };
  }
}
const sorted = Object.fromEntries(Object.keys(art).sort().map((k) => [k, art[k]]));
const body = Object.entries(sorted).map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v)},`).join('\n');
const text =
`// GENERATED by tools/write-manifest.mjs from the files in art/cards and art/ui. Do not edit by hand; run \`node tools/write-manifest.mjs\`.
// One entry per picture the page shows. Key: the card number for a card face ("ST01-005") and for a leader's
// front face; a leader's awakened face is "<number>/awakened" ("ST01-001/awakened"); UI plates use "ui/<name>".
// Shape: { file, kind: "leader" | "leader-awakened" | "card" | "ui", prompt: "<prompt id>" }; \`prompt\` is the
// key of the generation prompt (tools/build-art-prompts.mjs), so every picture traces to what made it.
// Every picture is an AI illustration generated from our own text descriptions, never from official art
// (docs/rights.md §2 and §7): label it AIイラスト / "AI-generated illustration" wherever it is shown.
(function () {
  const XS = (globalThis.XS = globalThis.XS || {});
  XS.ART = {
${body}
  };
})();
`;
fs.mkdirSync(path.dirname(P.manifest), { recursive: true });
fs.writeFileSync(P.manifest, text);
console.log(`write-manifest: ${Object.keys(sorted).length} entr${Object.keys(sorted).length === 1 ? 'y' : 'ies'} (${Object.keys(sorted).filter((k) => !k.startsWith('ui/')).length} of ${faceKeys(M.CARDS).length} faces, ${Object.keys(sorted).filter((k) => k.startsWith('ui/')).length} of ${uiKeys(M.IDENT).length} ui plates) -> ${rel(P.manifest)}${strays ? `; ${strays} stray file(s) skipped` : ''}`);
